import { createServer } from 'vite';
import { execSync } from 'node:child_process';
const own = (): string => execSync('netstat -ano -p tcp').toString().split('\n').filter((l) => l.includes('LISTENING') && l.trim().endsWith(' ' + process.pid)).map((l) => l.trim().split(/\s+/)[1]).join(' ');
process.on('uncaughtException', (e) => console.log('UNCAUGHT', String(e)));
const server = await createServer({ configFile: process.cwd() + '/vite.config.ts', server: { port: Number(process.argv[2]), host: true }, logLevel: 'info' });
await server.listen();
console.log('start |', own());
const gap = Number(process.argv[3]);
const a = server.restart().then(() => 'a ok', (e) => 'a err ' + String(e));
await new Promise((r) => setTimeout(r, gap));
const b = server.restart().then(() => 'b ok', (e) => 'b err ' + String(e));
console.log(await a, await b);
await new Promise((r) => setTimeout(r, 2000));
console.log('after |', own());
process.exit(0);
