/** Число для журнала: до сотых, без хвостовых нулей. */
function num(n: number): string {
  return String(Math.round(n * 100) / 100);
}

/** Контекст canvas, который записывает команды рисования. */
class Recorder implements GraphCanvas {
  readonly log: string[] = [];
  font = '';
  textAlign: CanvasTextAlign = 'start';
  textBaseline: CanvasTextBaseline = 'alphabetic';
  lineJoin: CanvasLineJoin = 'miter';
  private alpha = 1;
  private strokeColor: GraphCanvas['strokeStyle'] = '';
  private fillColor: GraphCanvas['fillStyle'] = '';
  private width = 1;

  private put(line: string): void {
    this.log.push(line);
  }

  get globalAlpha(): number { return this.alpha; }
  set globalAlpha(v: number) { this.alpha = v; this.put(`alpha ${num(v)}`); }
  get strokeStyle(): GraphCanvas['strokeStyle'] { return this.strokeColor; }
  set strokeStyle(v: GraphCanvas['strokeStyle']) { this.strokeColor = v; this.put(`stroke ${String(v)}`); }
  get fillStyle(): GraphCanvas['fillStyle'] { return this.fillColor; }
  set fillStyle(v: GraphCanvas['fillStyle']) { this.fillColor = v; this.put(`fill ${String(v)}`); }
  get lineWidth(): number { return this.width; }
  set lineWidth(v: number) { this.width = v; this.put(`width ${num(v)}`); }
  clearRect(x: number, y: number, w: number, h: number): void { this.put(`clear ${[x, y, w, h].map(num).join(' ')}`); }
  setLineDash(d: number[]): void { this.put(`dash ${d.join(',')}`); }
  beginPath(): void { this.put('begin'); }
  closePath(): void { this.put('close'); }
  moveTo(x: number, y: number): void { this.put(`move ${num(x)} ${num(y)}`); }
  lineTo(x: number, y: number): void { this.put(`line ${num(x)} ${num(y)}`); }
  rect(x: number, y: number, w: number, h: number): void { this.put(`rect ${[x, y, w, h].map(num).join(' ')}`); }
  roundRect(x: number, y: number, w: number, h: number, r: number): void { this.put(`roundRect ${[x, y, w, h, r].map(num).join(' ')}`); }
  arc(x: number, y: number, r: number, a0: number, a1: number): void { this.put(`arc ${[x, y, r, a0, a1].map(num).join(' ')}`); }
  stroke(): void { this.put('strokePath'); }
  fill(): void { this.put('fillPath'); }
  measureText(text: string): { width: number } { return { width: text.length * 6 }; }
  strokeText(text: string, x: number, y: number): void { this.put(`strokeText "${text}" ${num(x)} ${num(y)}`); }
  fillText(text: string, x: number, y: number): void { this.put(`fillText "${text}" ${num(x)} ${num(y)}`); }
}

/** Рисует кадр и возвращает журнал команд. */
function frame(nodes: SimNode[], links: SimLink[], cam: Camera, focus: DrawFocus, labelsAll = false, size = { w: 800, h: 600 }): string[] {
  const rec = new Recorder();
  drawGraph(rec, size, nodes, links, cam, focus, PAL, labelsAll);
  return rec.log;
}

function node(id: string, kind: SimNode['kind'], x: number | undefined, y: number | undefined, extra: Partial<SimNode> = {}): SimNode {
  return { id, kind, label: id, notReady: false, r: 5, x, y, ...extra };
}

